export function exitRule(strategy: StrategyId, patternId: string): ExitRule | null {
  if (!knownPatterns.some((pattern) => pattern.id === patternId)) return null;
  if (strategy === 1) return "classic";
  if (strategy === 2) return "scalp";
  if (strategy === 3) return "ladder";
  if (patternId === "liquidation_cascade" || patternId === "balanced_grind") return "ladder";
  if (patternId === "impulse_buy") return "impulse_partial";
  if (patternId === "price_led_momentum") return "classic";
  return null;
}

export function ruleLabel(rule: ExitRule | null, patternId: string): string {
  if (rule === "scalp") return "100% позиции при +5% цены; если цель не достигнута — стоп бота";
  if (rule === "ladder") return "25% при +5% · 25% при +10% · 50% при +15%; остаток — по стопу бота";
  if (rule === "impulse_partial") {
    return "PAPER: тейки 25% на +5% и +10% цены; остаток core под защитой, runner 20% отдельно";
  }
  if (rule === "classic" && patternId === "impulse_buy") {
    return "Классическая защита основной части (80%) и отдельный runner (20%)";
  }
  if (rule === "classic") {
    return "Классика: защита на +5% / +10%, затем trailing после +15%; без полного фикса на +5% или +15%";
  }
  return "Правила для этого паттерна не заданы";
}